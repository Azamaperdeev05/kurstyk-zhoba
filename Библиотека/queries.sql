-- 1. Қозғалыс кестесінен қайтарылған күні > берілген күні болатын жолдарды таңдау
CREATE PROCEDURE Тапсырма_1 AS
SET NOCOUNT ON;
SELECT * FROM Қозғалыс WHERE Қайтарылған_күні > Берілген_күні;
GO

-- 2. Оқырмандар кестесінен ... жылы туған оқырмандарды таңдау
CREATE PROCEDURE Тапсырма_2 @Туған_жылы INT AS
SET NOCOUNT ON;
SELECT * FROM Оқырмандар WHERE YEAR(Туған_күні) = @Туған_жылы;
GO

-- 3. Автор_аты_жөні кестесіне үш жаңа жол қосу (қайта іске қосқанда қайталанбайды)
CREATE PROCEDURE Тапсырма_3 AS
SET NOCOUNT ON;
INSERT INTO Автор_аты_жөні (Аты_жөні)
SELECT v.Аты_жөні
FROM (VALUES (N'Сүлейменов Олжас Омарұлы'),
             (N'Жансүгіров Ілияс'),
             (N'Пушкин Александр Сергеевич')) v(Аты_жөні)
WHERE NOT EXISTS (SELECT 1 FROM Автор_аты_жөні а WHERE а.Аты_жөні = v.Аты_жөні);
SELECT * FROM Автор_аты_жөні ORDER BY Автор_коды;
GO

-- 4. Кітаптың сөредегі даналарының кепілдік құны = қолжетімді саны * кепілдік құны
CREATE PROCEDURE Тапсырма_4 @Кітап_коды INT AS
SET NOCOUNT ON;
SELECT қ.Кітап_коды, к.Атауы AS Кітап, с.Атауы AS Сөре,
       қ.Қолжетімді_саны, қ.Кепілдік_құны,
       қ.Қолжетімді_саны * қ.Кепілдік_құны AS Сөредегі_кепілдік_құны
FROM Қор қ
JOIN Кітаптар к        ON к.Кітап_коды = қ.Кітап_коды
JOIN Сақтау_орындары с ON с.Сөре_коды = қ.Сөре_коды
WHERE қ.Кітап_коды = @Кітап_коды;
GO
