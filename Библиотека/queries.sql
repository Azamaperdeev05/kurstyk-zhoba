-------------------------------------------------- СҰРАНЫСТАР
-- 1. Әр сөредегі кітаптардың жалпы саны
CREATE PROCEDURE Сұраныс_1 AS
SET NOCOUNT ON;
SELECT с.Сөре_коды, с.Атауы AS Сөре, с.Орналасқан_жері,
       COUNT(қ.Кітап_коды)            AS Атау_саны,
       ISNULL(SUM(қ.Жалпы_саны), 0)   AS Барлық_дана
FROM Сақтау_орындары с
LEFT JOIN Қор қ ON қ.Сөре_коды = с.Сөре_коды
GROUP BY с.Сөре_коды, с.Атауы, с.Орналасқан_жері
ORDER BY с.Сөре_коды;
GO

-- 2. Оқырмандарда қандай кітаптың қанша данасы бар
CREATE PROCEDURE Сұраныс_2 AS
SET NOCOUNT ON;
SELECT ISNULL(к.Атауы, N'БАРЛЫҒЫ') AS Кітап,
       COUNT(*) AS Оқырмандағы_дана
FROM Қозғалыс з
JOIN Кітаптар к ON к.Кітап_коды = з.Кітап_коды
WHERE з.Қайтарылған_күні IS NULL
GROUP BY ROLLUP(к.Атауы)
ORDER BY GROUPING(к.Атауы), к.Атауы;
GO

-- 3. i-ші автордың оқырмандарға берілген және қайтарылмаған кітаптары
CREATE PROCEDURE Сұраныс_3 @Автор_коды INT AS
SET NOCOUNT ON;
SELECT к.Атауы AS Кітап, а.Аты_жөні AS Автор, о.Аты_жөні AS Оқырман,
       з.Берілген_күні, DATEADD(DAY, з.Мерзімі_күн, з.Берілген_күні) AS Қайтару_мерзімі
FROM Қозғалыс з
JOIN Авторлар ав      ON ав.Кітап_коды = з.Кітап_коды
JOIN Автор_аты_жөні а ON а.Автор_коды = ав.Автор_коды
JOIN Кітаптар к       ON к.Кітап_коды = з.Кітап_коды
JOIN Оқырмандар о     ON о.Оқырман_коды = з.Оқырман_коды
WHERE ав.Автор_коды = @Автор_коды AND з.Қайтарылған_күні IS NULL
ORDER BY з.Берілген_күні;
GO

-- 4. Авторы «...» болатын кітаптар тізімі
CREATE PROCEDURE Сұраныс_4 @Автордың_аты_жөні NVARCHAR(100) AS
SET NOCOUNT ON;
SELECT к.Кітап_коды, к.Атауы AS Кітап, а.Аты_жөні AS Автор,
       б.Атауы AS Баспа, к.Шыққан_жылы
FROM Кітаптар к
JOIN Авторлар ав      ON ав.Кітап_коды = к.Кітап_коды
JOIN Автор_аты_жөні а ON а.Автор_коды = ав.Автор_коды
JOIN Баспалар б       ON б.Баспа_коды = к.Баспа_коды
WHERE а.Аты_жөні LIKE N'%' + @Автордың_аты_жөні + N'%'
ORDER BY к.Атауы;
GO

-- 5. Кітапхананың кәмелетке толмаған оқырмандары (18 жасқа дейін)
CREATE PROCEDURE Сұраныс_5 AS
SET NOCOUNT ON;
DECLARE @бүгін DATE = GETDATE();
SELECT Оқырман_коды, Аты_жөні, Туған_күні,
       DATEDIFF(YEAR, Туған_күні, @бүгін)
         - CASE WHEN DATEADD(YEAR, DATEDIFF(YEAR, Туған_күні, @бүгін), Туған_күні) > @бүгін
                THEN 1 ELSE 0 END AS Жасы,
       Жұмыс_оқу_орны
FROM Оқырмандар
WHERE DATEADD(YEAR, 18, Туған_күні) > @бүгін
ORDER BY Туған_күні DESC;
GO

-------------------------------------------------- ЕСЕПТЕР
-- 1. i-ші кітапханашының j-ші айдағы кітап қозғалысы туралы есебі
CREATE PROCEDURE Есеп_1 @Кітапханашы_коды INT, @Жыл INT, @Ай INT AS
SET NOCOUNT ON;
SELECT з.Операция_коды, з.Берілген_күні, к.Атауы AS Кітап, о.Аты_жөні AS Оқырман,
       з.Мерзімі_күн, ISNULL(CONVERT(NVARCHAR(20), з.Қайтарылған_күні, 104), N'қайтарылмаған') AS Қайтарылуы,
       кш.Аты_жөні AS Кітапханашы
FROM Қозғалыс з
JOIN Кітаптар к        ON к.Кітап_коды = з.Кітап_коды
JOIN Оқырмандар о      ON о.Оқырман_коды = з.Оқырман_коды
JOIN Кітапханашылар кш ON кш.Кітапханашы_коды = з.Кітапханашы_коды
WHERE з.Кітапханашы_коды = @Кітапханашы_коды
  AND YEAR(з.Берілген_күні) = @Жыл AND MONTH(з.Берілген_күні) = @Ай
ORDER BY з.Берілген_күні;
GO

-- 2. i-ші кітапханашының қаржылық есебі (қабылданған айыппұлдар)
CREATE PROCEDURE Есеп_2 @Кітапханашы_коды INT AS
SET NOCOUNT ON;
SELECT ISNULL(о.Аты_жөні, N'БАРЛЫҒЫ') AS Оқырман,
       COUNT(*)              AS Айыппұл_саны,
       SUM(а.Айыппұл_сомасы) AS Сомасы
FROM Айыппұл а
JOIN Оқырмандар о ON о.Оқырман_коды = а.Оқырман_коды
WHERE а.Кітапханашы_коды = @Кітапханашы_коды
GROUP BY ROLLUP(о.Аты_жөні)
ORDER BY GROUPING(о.Аты_жөні), о.Аты_жөні;
GO

-- 3. i-ші күні кітап алған оқырмандар тізімі
CREATE PROCEDURE Есеп_3 @Күні DATE AS
SET NOCOUNT ON;
SELECT о.Оқырман_коды, о.Аты_жөні AS Оқырман, о.Телефон,
       к.Атауы AS Кітап, кш.Аты_жөні AS Кітапханашы
FROM Қозғалыс з
JOIN Оқырмандар о      ON о.Оқырман_коды = з.Оқырман_коды
JOIN Кітаптар к        ON к.Кітап_коды = з.Кітап_коды
JOIN Кітапханашылар кш ON кш.Кітапханашы_коды = з.Кітапханашы_коды
WHERE з.Берілген_күні = @Күні
ORDER BY Оқырман;
GO

