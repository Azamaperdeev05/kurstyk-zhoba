-------------------------------------------------- СҰРАНЫСТАР
-- 1. Әр жазылушы жазылған басылымдар саны
CREATE PROCEDURE Сұраныс_1 AS
SET NOCOUNT ON;
SELECT жш.Жазылушы_коды, жш.Аты_жөні_атауы AS Жазылушы,
       COUNT(ж.Жазылым_коды) AS Басылым_саны
FROM Жазылушы жш
LEFT JOIN Жазылым ж ON ж.Жазылушы_коды = жш.Жазылушы_коды
GROUP BY жш.Жазылушы_коды, жш.Аты_жөні_атауы
ORDER BY Басылым_саны DESC, Жазылушы;
GO

-- 2. i-ші елдің j-ші тілдегі журналдарының тізімі
CREATE PROCEDURE Сұраныс_2 @Ел_коды INT, @Тіл_коды INT AS
SET NOCOUNT ON;
SELECT б.Басылым_индексі, б.Атауы, е.Атауы AS Ел, т.Атауы AS Тілі, б.Айлық_бағасы
FROM Басылым б
JOIN Басылым_түрі бт ON бт.Басылым_түрі_коды = б.Басылым_түрі_коды
JOIN Елдер е         ON е.Ел_коды = б.Ел_коды
JOIN Басылым_тілі т  ON т.Тіл_коды = б.Тіл_коды
WHERE бт.Атауы = N'журнал' AND б.Ел_коды = @Ел_коды AND б.Тіл_коды = @Тіл_коды
ORDER BY б.Атауы;
GO

-- 3. i-ші қызметкер ағымдағы айда рәсімдеген жазылымдар
CREATE PROCEDURE Сұраныс_3 @Қызметкер_коды INT AS
SET NOCOUNT ON;
SELECT ж.Жазылым_коды, ж.Жазылу_күні, жш.Аты_жөні_атауы AS Жазылушы,
       б.Атауы AS Басылым, ж.Жазылу_мерзімі, қ.Аты_жөні AS Қызметкер
FROM Жазылым ж
JOIN Жазылушы жш    ON жш.Жазылушы_коды = ж.Жазылушы_коды
JOIN Басылым б      ON б.Басылым_индексі = ж.Басылым_индексі
JOIN Қызметкерлер қ ON қ.Қызметкер_коды = ж.Қызметкер_коды
WHERE ж.Қызметкер_коды = @Қызметкер_коды
  AND YEAR(ж.Жазылу_күні) = YEAR(GETDATE())
  AND MONTH(ж.Жазылу_күні) = MONTH(GETDATE())
ORDER BY ж.Жазылу_күні;
GO

-- 4. Бағасы ... мен ... аралығындағы журналдар тізімі
CREATE PROCEDURE Сұраныс_4 @Баға_бастап DECIMAL(10,2), @Баға_дейін DECIMAL(10,2) AS
SET NOCOUNT ON;
SELECT б.Басылым_индексі, б.Атауы, б.Айлық_бағасы
FROM Басылым б
JOIN Басылым_түрі бт ON бт.Басылым_түрі_коды = б.Басылым_түрі_коды
WHERE бт.Атауы = N'журнал' AND б.Айлық_бағасы BETWEEN @Баға_бастап AND @Баға_дейін
ORDER BY б.Айлық_бағасы;
GO

-- 5. «... көшесі» мекенжайында тұратын жазылушылар тізімі
CREATE PROCEDURE Сұраныс_5 @Көше NVARCHAR(100) AS
SET NOCOUNT ON;
SELECT Жазылушы_коды, Аты_жөні_атауы AS Жазылушы, Мекенжай, Телефон
FROM Жазылушы
WHERE Мекенжай LIKE N'%' + @Көше + N'%'
ORDER BY Жазылушы;
GO

-------------------------------------------------- ЕСЕПТЕР
-- 1. i-ші жылғы j-ші пошта бөлімшесі бойынша жазылған басылымдардың сандық-сомалық есебі
--    Сома = айлық баға * мерзім * (100 - жеңілдік %) / 100
CREATE PROCEDURE Есеп_1 @Жыл INT, @Бөлімше_коды INT AS
SET NOCOUNT ON;
SELECT ISNULL(б.Атауы, N'БАРЛЫҒЫ')     AS Басылым,
       COUNT(*)                        AS Жазылым_саны,
       SUM(ж.Жазылу_мерзімі)           AS Барлық_айлар,
       CAST(SUM(б.Айлық_бағасы * ж.Жазылу_мерзімі * (100 - жш.Жеңілдік_пайызы) / 100) AS DECIMAL(12,2)) AS Сомасы
FROM Жазылым ж
JOIN Басылым б   ON б.Басылым_индексі = ж.Басылым_индексі
JOIN Жазылушы жш ON жш.Жазылушы_коды = ж.Жазылушы_коды
WHERE YEAR(ж.Жазылу_күні) = @Жыл AND жш.Бөлімше_коды = @Бөлімше_коды
GROUP BY ROLLUP(б.Атауы)
ORDER BY GROUPING(б.Атауы), б.Атауы;
GO

-- 2. i-ші қызметкердің j-ші күнгі қаржылық есебі (қабылданған төлемдер)
CREATE PROCEDURE Есеп_2 @Қызметкер_коды INT, @Күні DATE AS
SET NOCOUNT ON;
SELECT ISNULL(жш.Аты_жөні_атауы, N'БАРЛЫҒЫ') AS Жазылушы,
       COUNT(*)      AS Төлем_саны,
       SUM(т.Сомасы) AS Сомасы
FROM Төлем т
JOIN Жазылушы жш ON жш.Жазылушы_коды = т.Жазылушы_коды
WHERE т.Қызметкер_коды = @Қызметкер_коды AND т.Күні = @Күні
GROUP BY ROLLUP(жш.Аты_жөні_атауы)
ORDER BY GROUPING(жш.Аты_жөні_атауы), жш.Аты_жөні_атауы;
GO

-- 3. Басылымдарды пошта бөлімшесінен алатын i-ші бөлімше жазылушыларының тізімі
CREATE PROCEDURE Есеп_3 @Бөлімше_коды INT AS
SET NOCOUNT ON;
SELECT жш.Аты_жөні_атауы AS Жазылушы, жш.Мекенжай, жш.Телефон,
       б.Атауы AS Басылым, ж.Жазылу_күні, ж.Жазылу_мерзімі
FROM Жазылушы жш
JOIN Жеткізу_түрі жт ON жт.Жеткізу_түрі_коды = жш.Жеткізу_түрі_коды
JOIN Жазылым ж       ON ж.Жазылушы_коды = жш.Жазылушы_коды
JOIN Басылым б       ON б.Басылым_индексі = ж.Басылым_индексі
WHERE жш.Бөлімше_коды = @Бөлімше_коды AND жт.Атауы = N'пошта бөлімшесі'
ORDER BY Жазылушы, Басылым;
GO

