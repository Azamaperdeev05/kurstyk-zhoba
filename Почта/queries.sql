-- 1. Жазылым кестесінен жазылу мерзімі 12 ай болатын жолдарды таңдау
CREATE PROCEDURE Тапсырма_1 AS
SET NOCOUNT ON;
SELECT * FROM Жазылым WHERE Жазылу_мерзімі = 12;
GO

-- 2. Басылым кестесінен i-ші түрдегі, j-ші тілде шығатын басылымдарды таңдау
CREATE PROCEDURE Тапсырма_2 @Басылым_түрі_коды INT, @Тіл_коды INT AS
SET NOCOUNT ON;
SELECT * FROM Басылым
WHERE Басылым_түрі_коды = @Басылым_түрі_коды AND Тіл_коды = @Тіл_коды;
GO

-- 3. Басылым_түрі кестесіне үш жаңа жол қосу (қайта іске қосқанда қайталанбайды)
CREATE PROCEDURE Тапсырма_3 AS
SET NOCOUNT ON;
INSERT INTO Басылым_түрі (Атауы)
SELECT v.Атауы
FROM (VALUES (N'бюллетень'), (N'альманах'), (N'каталог')) v(Атауы)
WHERE NOT EXISTS (SELECT 1 FROM Басылым_түрі бт WHERE бт.Атауы = v.Атауы);
SELECT * FROM Басылым_түрі ORDER BY Басылым_түрі_коды;
GO

-- 4. Басылымның жазылған данасы = жалпы саны – қолжетімді саны
CREATE PROCEDURE Тапсырма_4 @Басылым_индексі INT AS
SET NOCOUNT ON;
SELECT Басылым_индексі, Атауы, Жалпы_саны, Қолжетімді_саны,
       Жалпы_саны - Қолжетімді_саны AS Жазылған_дана
FROM Басылым
WHERE Басылым_индексі = @Басылым_индексі;
GO
