-- Қолжетімді сан = жалпы сан – басылымға рәсімделген жазылымдар саны
UPDATE б SET Қолжетімді_саны = Жалпы_саны
    - (SELECT COUNT(*) FROM Жазылым ж WHERE ж.Басылым_индексі = б.Басылым_индексі)
FROM Басылым б;

-- Әр жазылымға бір төлем: айлық баға * мерзім * (100 - жеңілдік %) / 100
INSERT INTO Төлем (Жазылушы_коды, Күні, Сомасы, Қызметкер_коды)
SELECT ж.Жазылушы_коды, ж.Жазылу_күні,
       CAST(б.Айлық_бағасы * ж.Жазылу_мерзімі * (100 - жш.Жеңілдік_пайызы) / 100 AS DECIMAL(10,2)),
       ж.Қызметкер_коды
FROM Жазылым ж
JOIN Басылым б   ON б.Басылым_индексі = ж.Басылым_индексі
JOIN Жазылушы жш ON жш.Жазылушы_коды = ж.Жазылушы_коды
ORDER BY ж.Жазылым_коды;
